package com.honghu.ut.test.ai.assigment.testdeepseekr1.skill.core;

/**
 * 工具危险等级。
 *
 * <p>技能系统中，每一个可被模型调用的工具都应该有危险等级。后续接入“删除仓库”、
 * “发邮件”、“执行命令”这类高风险能力时，后端和前端都可以根据这个枚举决定是否需要
 * 二次确认、权限拦截或审计告警。</p>
 */
public enum DangerLevel {
    /**
     * 安全工具。
     *
     * <p>适合只读查询、数学计算、时间日期、知识库检索等不会修改外部状态的工具。
     * 默认等级使用 SAFE，是为了让普通内置工具不需要额外确认即可被模型调用。</p>
     */
    SAFE,
    /**
     * 谨慎工具。
     *
     * <p>适合可能访问外部网络、消耗额度、读取用户敏感上下文，但一般不会直接造成
     * 不可逆数据修改的工具。</p>
     */
    CAUTION,
    /**
     * 危险工具。
     *
     * <p>适合删除数据、发送消息、提交代码、执行命令等可能造成外部副作用的工具。
     * 这类工具后续应该触发审批流程，让用户显式确认。</p>
     */
    DANGEROUS
}
